import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

export async function buildPages(root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')){
 const destination=path.join(root,'_site'),seen=new Set(),pending=['index.html'];
 // Discover only browser dependencies. Tests, local logs and documents are never site assets.
 while(pending.length){const relative=pending.shift();if(seen.has(relative))continue;
  const absolute=path.resolve(root,relative);if(!absolute.startsWith(root+path.sep))throw Error('Asset outside project: '+relative);
  const source=await fs.readFile(absolute,'utf8');seen.add(relative);
  const references=[];
  if(relative.endsWith('.html'))for(const match of source.matchAll(/(?:src|href)=["']([^"']+)["']/g))references.push(match[1]);
  if(relative.endsWith('.mjs'))for(const match of source.matchAll(/(?:from\s*|import\s*)["'](\.\.?\/[^"']+)["']/g))references.push(match[1]);
  if(relative.endsWith('.css'))for(const match of source.matchAll(/url\(["']?([^\s)"']+)/g))references.push(match[1]);
  for(const ref of references){if(/^(?:data:|https?:|#)/.test(ref))continue;if(ref.startsWith('/'))throw Error('Root-relative asset breaks project hosting: '+ref);
   pending.push(path.normalize(path.join(path.dirname(relative),ref.split(/[?#]/)[0])));
  }
 }
 // This exact output directory is generated by this script; never delete an arbitrary target.
 if(path.resolve(destination)!==path.resolve(root,'_site'))throw Error('Invalid build target');
 await fs.mkdir(destination,{recursive:true});
 // Clean files from an earlier build without following links outside the output directory.
 for(const item of await fs.readdir(destination,{withFileTypes:true})){if(item.isDirectory()||item.isSymbolicLink())throw Error('Unexpected directory/link in output: '+item.name);await fs.unlink(path.join(destination,item.name));}
 for(const relative of seen){const target=path.join(destination,relative);await fs.mkdir(path.dirname(target),{recursive:true});await fs.copyFile(path.join(root,relative),target);}
 await fs.writeFile(path.join(destination,'.nojekyll'),'');
 const manifest={version:JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8')).version,files:[...seen].sort()};
 await fs.writeFile(path.join(destination,'build-info.json'),JSON.stringify(manifest,null,2)+'\n');
 return manifest;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){const manifest=await buildPages();console.log(`Pages ready: ${manifest.files.length} browser assets, version ${manifest.version}`);}
